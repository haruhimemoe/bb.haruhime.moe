/** The banner's glyphs by character (capitals), each row drawn with █ and spaces. */
export const BANNER_FONT: Readonly<Record<string, readonly string[]>> = Object.fromEntries(
  Object.entries(FONT_SOURCE).map(([char, rows]) => [
    char,
    rows.map((row) => row.replaceAll("#", "█").replaceAll(".", " ")),
  ]),
);

